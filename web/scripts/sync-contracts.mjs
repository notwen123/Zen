#!/usr/bin/env node
// Generates typed ABIs + addresses for the web app from the real build artifacts:
//   ../out/<Contract>.sol/<Contract>.json   (forge build)
//   ../deployments/46630.json              (script/DeployStockback.s.sol + testnet ops)
//   ../broadcast/DeployStockback.s.sol/46630/run-latest.json  (deployment block)
// Run after `forge build` or a redeploy:  npm run sync-contracts
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const out = resolve(root, "web/lib/generated");
const CONTRACTS = ["ReceiptCommitmentRegistry", "EligibilityPolicy", "RewardPolicy", "RewardPool", "BrandVaultFactory", "BrandVault"];

let abis = "// GENERATED by web/scripts/sync-contracts.mjs from forge artifacts. Do not edit.\n";
for (const c of CONTRACTS) {
  const { abi } = JSON.parse(readFileSync(resolve(root, `out/${c}.sol/${c}.json`), "utf8"));
  abis += `\nexport const ${c[0].toLowerCase() + c.slice(1)}Abi = ${JSON.stringify(abi, null, 1)} as const;\n`;
}
writeFileSync(resolve(out, "abis.ts"), abis);

const chainId = 46630;
const d = JSON.parse(readFileSync(resolve(root, `deployments/${chainId}.json`), "utf8"));
const bpath = resolve(root, `broadcast/DeployStockback.s.sol/${chainId}/run-latest.json`);
const fromBlock = existsSync(bpath)
  ? Math.min(...JSON.parse(readFileSync(bpath, "utf8")).receipts.map((r) => parseInt(r.blockNumber, 16)))
  : 0;
const deployment = { chainId, fromBlock, ...d };
writeFileSync(
  resolve(out, "deployment.ts"),
  `// GENERATED by web/scripts/sync-contracts.mjs from deployments/${chainId}.json. Do not edit.\n` +
    `export const deployment = ${JSON.stringify(deployment, null, 2)} as const;\n`,
);
// Measured Stylus-vs-Solidity benchmark (benchmarks/run_onchain.sh), baked in so the web app builds standalone.
const benchPath = resolve(root, `benchmarks/results/onchain-${chainId}.md`);
const benchRows = existsSync(benchPath)
  ? [...readFileSync(benchPath, "utf8").matchAll(/^\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|/gm)].map((m) => ({
      batch: Number(m[1]),
      solidity: /^\d+$/.test(m[2]) ? Number(m[2]) : null,
      stylus: /^\d+$/.test(m[3]) ? Number(m[3]) : null,
    }))
  : [];
writeFileSync(
  resolve(out, "benchmark.ts"),
  `// GENERATED by web/scripts/sync-contracts.mjs from benchmarks/results/onchain-${chainId}.md. Do not edit.\n` +
    `export const benchmarkRows: { batch: number; solidity: number | null; stylus: number | null }[] = ${JSON.stringify(benchRows, null, 2)};\n`,
);
console.log(`synced ${CONTRACTS.length} ABIs + deployment (chain ${chainId}, fromBlock ${fromBlock})`);
